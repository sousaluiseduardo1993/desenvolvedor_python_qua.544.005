# Match case - dias da semana

dia_semana = int(input("Digite o dia da semana (1 a 7): "))

if dia_semana == 1:
    print("Domingo")

elif dia_semana == 2:
    print("Segunda-feira")

elif dia_semana == 3:
    print("Terça-feira")

elif dia_semana == 4:
    print("Quarta-feira")

elif dia_semana == 5:
    print("Quinta-feira")

elif dia_semana == 6:
    print("Sexta-feira")

elif dia_semana == 7:
    print("Sábado")

else:
    print("Dia da semana inválido")